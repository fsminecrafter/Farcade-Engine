#!/usr/bin/env python3
"""Turns files into a C++ source with byte arrays.

usage: embed.py out.cpp name1=path1 [name2=path2 ...]
Each file becomes `extern const unsigned char name[]` and
`extern const unsigned int name_size`.
"""
import sys

def main():
    out = sys.argv[1]
    lines = ["// Generated by tools/embed.py; do not edit.\n"]
    for arg in sys.argv[2:]:
        name, path = arg.split("=", 1)
        data = open(path, "rb").read()
        lines.append(f"extern const unsigned char {name}[];\nextern const unsigned int {name}_size;\n")
        lines.append(f"alignas(16) const unsigned char {name}[] = {{\n")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
        lines.append("};\n")
        lines.append(f"const unsigned int {name}_size = {len(data)};\n")
    open(out, "w").write("".join(lines))

if __name__ == "__main__":
    main()
