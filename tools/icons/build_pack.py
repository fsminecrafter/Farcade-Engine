#!/usr/bin/env python3
"""The editor's icon pack: vector .img icons as font glyphs.

The icons are drawn as SVG (editor/icons/*.svg, see editor/icons/README.md),
converted to Minimal-OS vector images (editor/icons/img/*.img, the .img
format's vector mode) and embedded in the editor, which rasterizes them
into its font atlas at whatever size the UI needs (editor/src/icon_font.cpp).
Every icon is a character in the Private Use Area, so it can sit in any
label: ImGui::Text(FE_ICON_SAVE " Save").

  build_pack.py convert <mosmedia> [names...]  SVG -> editor/icons/img/<name>.img
                                               (all icons and the logo by default)
  build_pack.py header                         writes editor/src/icon_glyphs.h
  build_pack.py source <out.cpp>               the embedded pack (build step)

Codepoints come from editor/icons/codepoints.txt: new icons are appended,
existing ones never move, so saved layouts and strings stay valid.
"""
import os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ICONS = os.path.join(ROOT, "editor", "icons")
IMG = os.path.join(ICONS, "img")
CODEPOINTS = os.path.join(ICONS, "codepoints.txt")
HEADER = os.path.join(ROOT, "editor", "src", "icon_glyphs.h")
LOGO_SVG = os.path.join(ROOT, "docs", "logo", "farcade-logo.svg")
FIRST = 0xE000


def svg_names():
    return sorted(f[:-4] for f in os.listdir(ICONS) if f.endswith(".svg"))


def codepoints():
    """name -> codepoint, appending icons that have none yet."""
    table, order = {}, []
    if os.path.exists(CODEPOINTS):
        for line in open(CODEPOINTS):
            line = line.split("#")[0].strip()
            if not line:
                continue
            cp, name = line.split()
            table[name] = int(cp, 16)
            order.append(name)
    nxt = max(table.values(), default=FIRST - 1) + 1
    changed = False
    for name in ["logo"] + svg_names():
        if name not in table:
            table[name] = nxt
            order.append(name)
            nxt += 1
            changed = True
    if changed or not os.path.exists(CODEPOINTS):
        with open(CODEPOINTS, "w") as f:
            f.write("# Icon codepoints (Private Use Area). Appended by tools/icons/build_pack.py;\n")
            f.write("# never reorder or reuse a codepoint.\n")
            for name in order:
                f.write(f"{table[name]:04X} {name}\n")
    return table, order


def utf8_escape(cp):
    return "".join(f"\\x{b:02X}" for b in chr(cp).encode("utf-8"))


def write_header():
    table, order = codepoints()
    lines = [
        "// Icon glyphs: every editor icon is a character in the Private Use Area of",
        "// the editor's fonts, drawn from a vector .img (editor/src/icon_font.h).",
        "// Generated by tools/icons/build_pack.py from editor/icons/codepoints.txt; do not edit.",
        "#pragma once",
        "",
        f"#define FE_ICON_FIRST 0x{min(table.values()):04X}",
        f"#define FE_ICON_LAST 0x{max(table.values()):04X}",
        "",
    ]
    for name in order:
        lines.append(f'#define FE_ICON_{name.upper():<20} "{utf8_escape(table[name])}"   // U+{table[name]:04X}')
    lines.append("")
    lines.append("namespace fe {")
    lines.append("// The codepoint of an icon by its file name (editor/icons/<name>.svg); 0 if unknown.")
    lines.append("unsigned icon_codepoint(const char* name);")
    lines.append("}  // namespace fe")
    open(HEADER, "w").write("\n".join(lines) + "\n")
    print(f"build_pack: {HEADER} ({len(order)} icons)")


def write_source(out):
    table, order = codepoints()
    lines = ["// Generated by tools/icons/build_pack.py; do not edit.",
             "#include <stddef.h>", "#include <string.h>", "#include \"icon_font.h\"", "",
             "namespace fe {", ""]
    entries = []
    for name in order:
        path = os.path.join(IMG, name + ".img")
        if not os.path.exists(path):
            continue
        data = open(path, "rb").read()
        sym = "icon_img_" + name
        lines.append(f"alignas(16) static const unsigned char {sym}[] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        entries.append((name, table[name], sym, len(data)))
    lines.append("")
    lines.append(f"const IconPackEntry kIconPack[] = {{")
    for name, cp, sym, n in entries:
        lines.append(f'    {{ "{name}", 0x{cp:04X}u, {sym}, {n}u }},')
    lines.append("};")
    lines.append(f"const unsigned kIconPackCount = {len(entries)}u;")
    lines.append("")
    lines.append("unsigned icon_codepoint(const char* name) {")
    lines.append("    for (unsigned i = 0; i < kIconPackCount; i++)")
    lines.append("        if (strcmp(kIconPack[i].name, name) == 0) return kIconPack[i].codepoint;")
    lines.append("    return 0;")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace fe")
    open(out, "w").write("\n".join(lines) + "\n")


def convert(mosmedia, names):
    os.makedirs(IMG, exist_ok=True)
    if not names:
        names = ["logo"] + svg_names()
    for name in names:
        src = LOGO_SVG if name == "logo" else os.path.join(ICONS, name + ".svg")
        dst = os.path.join(IMG, name + ".img")
        r = subprocess.run([mosmedia, "vimg", src, dst], capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f"build_pack: {name}: {r.stdout}{r.stderr}")
    print(f"build_pack: converted {len(names)} icons into {IMG}")


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    cmd = sys.argv[1]
    if cmd == "header":
        write_header()
    elif cmd == "source" and len(sys.argv) == 3:
        write_source(sys.argv[2])
    elif cmd == "convert" and len(sys.argv) >= 3:
        convert(sys.argv[2], sys.argv[3:])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
